    public CadastroAnime(br.com.ubiani.model.Anime anime) {
    this();

    idAnimeEdicao = anime.getIdAnimes();

    txtTitulo.setText(anime.getTitulo());
    txtDescricao.setText(anime.getDescricao());

    cbAnoLancamento.setSelectedItem(
        String.valueOf(anime.getAnoDeLancamento())
    );

    int classificacao = anime.getClassificacao();

    rbLivre.setSelected(classificacao == 0);
    rb10.setSelected(classificacao == 10);
    rb12.setSelected(classificacao == 12);
    rb14.setSelected(classificacao == 14);
    rb16.setSelected(classificacao == 16);
    rb18.setSelected(classificacao == 18);

    for (int i = 0; i < generosDisponiveis.size(); i++) {
        if (generosDisponiveis.get(i).getIdGenero()
                == anime.getGeneroIdGenero()) {

            cbGenero.setSelectedIndex(i + 1);
            break;
        }
    }
}

