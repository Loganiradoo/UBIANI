    private void btnSalvarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnSalvarActionPerformed
try {

    String titulo = txtTitulo.getText().trim();
    String descricao = txtDescricao.getText().trim();

    if (titulo.isEmpty() || descricao.isEmpty()
            || cbAnoLancamento.getSelectedIndex() == 0
            || cbGenero.getSelectedIndex() == 0) {

        javax.swing.JOptionPane.showMessageDialog(
                this, "Preencha todos os campos!");
        return;
    }

    int classificacao = -1;

    if (rbLivre.isSelected()) {
        classificacao = 0;
    } else if (rb10.isSelected()) {
        classificacao = 10;
    } else if (rb12.isSelected()) {
        classificacao = 12;
    } else if (rb14.isSelected()) {
        classificacao = 14;
    } else if (rb16.isSelected()) {
        classificacao = 16;
    } else if (rb18.isSelected()) {
        classificacao = 18;
    }

    if (classificacao == -1) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Selecione uma classificação!");
        return;
    }

    int ano = Integer.parseInt(
            cbAnoLancamento.getSelectedItem().toString());

    int generoId = generosDisponiveis.get(
        cbGenero.getSelectedIndex() - 1
    ).getIdGenero();

    br.com.ubiani.model.Anime anime =
            new br.com.ubiani.model.Anime(
                    idAnimeEdicao == null ? 0 : idAnimeEdicao,
                    titulo, descricao,
                    classificacao, ano, generoId);

    br.com.ubiani.dao.AnimeDAO dao =
            new br.com.ubiani.dao.AnimeDAO();

    if (idAnimeEdicao == null) {
        dao.cadastrar(anime);

        javax.swing.JOptionPane.showMessageDialog(
                this, "Anime cadastrado com sucesso!");
    } else {
        dao.atualizar(anime);

        javax.swing.JOptionPane.showMessageDialog(
                this, "Anime atualizado com sucesso!");
    }

    dispose();

} catch (NumberFormatException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this, "Verifique os valores numéricos!");

} catch (java.sql.SQLException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this, "Erro ao salvar anime: " + e.getMessage());
}
    }//GEN-LAST:event_btnSalvarActionPerformed

