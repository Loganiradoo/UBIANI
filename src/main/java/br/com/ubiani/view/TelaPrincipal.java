 private void carregarAnimes() {

    br.com.ubiani.dao.AnimeDAO animeDAO =
            new br.com.ubiani.dao.AnimeDAO();

    try {

        java.util.List<br.com.ubiani.model.Anime> animes =
                animeDAO.listarTodos();

        javax.swing.table.DefaultTableModel modelo =
                (javax.swing.table.DefaultTableModel) tblAnimes.getModel();

        modelo.setRowCount(0);

        for (br.com.ubiani.model.Anime anime : animes) {

            modelo.addRow(new Object[]{
                anime.getIdAnimes(),
                anime.getTitulo(),
                anime.getClassificacao(),
                anime.getAnoDeLancamento(),
                anime.getGeneroIdGenero()
            });
        }

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this,
                "Erro ao carregar os animes: " + e.getMessage()
        );
    }
}

