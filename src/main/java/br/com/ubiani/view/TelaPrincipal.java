    private void btnPesquisarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnPesquisarActionPerformed

        
String pesquisa = txtPesquisa.getText().trim();

if (pesquisa.equals("Selecione o título do anime...")) {
    pesquisa = "";
}

try {

    br.com.ubiani.dao.AnimeDAO dao =
            new br.com.ubiani.dao.AnimeDAO();

    java.util.List<br.com.ubiani.model.Anime> animes;

    if (pesquisa.isEmpty()) {
        animes = dao.listarTodos();
    } else {
        animes = dao.buscarPorTitulo(pesquisa);
    }

    javax.swing.table.DefaultTableModel modelo =
            (javax.swing.table.DefaultTableModel) tblAnimes.getModel();

    modelo.setRowCount(0);

    for (br.com.ubiani.model.Anime anime : animes) {

        modelo.addRow(new Object[]{
            anime.getIdAnimes(),
            anime.getTitulo(),
            anime.getClassificacao(),
            anime.getAnoDeLancamento(),
            anime.getGeneroIdGenero()
        });
    }

    if (animes.isEmpty()) {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Nenhum anime encontrado!");
    }

} catch (java.sql.SQLException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this, "Erro ao pesquisar: " + e.getMessage());
}

    }//GEN-LAST:event_btnPesquisarActionPerformed

    private void btnEditarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnEditarActionPerformed

        int linhaSelecionada = tblAnimes.getSelectedRow();

if (linhaSelecionada == -1) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Selecione um anime para editar!");
    return;
}

try {

    int idAnime = Integer.parseInt(
            tblAnimes.getValueAt(linhaSelecionada, 0).toString()
    );

    br.com.ubiani.dao.AnimeDAO dao =
            new br.com.ubiani.dao.AnimeDAO();

    br.com.ubiani.model.Anime anime =
            dao.buscarPorId(idAnime);

    if (anime != null) {

        
CadastroAnime telaEdicao = new CadastroAnime(anime);
telaEdicao.setLocationRelativeTo(this);

telaEdicao.addWindowListener(new java.awt.event.WindowAdapter() {
    @Override
    public void windowClosed(java.awt.event.WindowEvent evt) {
        carregarAnimes();
    }
});

telaEdicao.setVisible(true);


    } else {
        javax.swing.JOptionPane.showMessageDialog(
                this, "Anime não encontrado!");
    }

} catch (java.sql.SQLException e) {

    javax.swing.JOptionPane.showMessageDialog(
            this, "Erro ao buscar anime: " + e.getMessage());
}
    }//GEN-LAST:event_btnEditarActionPerformed

    private void btnExcluirActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnExcluirActionPerformed

        int linhaSelecionada = tblAnimes.getSelectedRow();

if (linhaSelecionada == -1) {
    javax.swing.JOptionPane.showMessageDialog(
            this, "Selecione um anime para excluir!");
    return;
}

int resposta = javax.swing.JOptionPane.showConfirmDialog(
        this,
        "Tem certeza de que deseja excluir este anime?",
        "Confirmar exclusão",
        javax.swing.JOptionPane.YES_NO_OPTION
);

if (resposta == javax.swing.JOptionPane.YES_OPTION) {

    try {

        int idAnime = Integer.parseInt(
                tblAnimes.getValueAt(linhaSelecionada, 0).toString()
        );

        br.com.ubiani.dao.AnimeDAO dao =
                new br.com.ubiani.dao.AnimeDAO();

        dao.excluir(idAnime);

        javax.swing.JOptionPane.showMessageDialog(
                this, "Anime excluído com sucesso!");

        carregarAnimes();

    } catch (java.sql.SQLException e) {

        javax.swing.JOptionPane.showMessageDialog(
                this, "Erro ao excluir anime: " + e.getMessage());
    }
}
    }//GEN-LAST:event_btnExcluirActionPerformed

